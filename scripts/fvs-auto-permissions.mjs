#!/usr/bin/env node
// Permission check for the auto track: which run steps would stop on an approval prompt, and a minimal
// project allowlist for exactly those steps.
//
// A rule file cannot predict a prompt: an ask rule beats an allow rule, a hook can ask although a rule allows,
// and a wildcard ask rule matches words inside a command's text. So the check runs one harmless live instance
// of each step (`plan` lists them) while the user is present. The agent cannot see prompts, so the user says
// which steps prompted and `record` keeps the answer. `write-allowlist` writes rules only for the steps that
// prompted, only from the closed catalog below, and only for the exact rule text the user confirmed (the
// confirmation is the digest that the preview prints). No rule it writes names a GitHub comment, review or
// merge, another remote, another branch namespace or a wildcard program. A wildcard in an allow rule still
// matches the rest of the command text, so the push rules come with deny rules for the usual force, delete
// and refspec spellings; those are not a boundary (see the permissions page), remote branch protection is.
//
// It reads no standard input and does not touch the engine's state or externals files; the answers live in
// their own record, .formalising/auto-fv/permissions.json.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const RECORD_FILE = '.formalising/auto-fv/permissions.json';
export const SCRATCH_DIR = '.formalising/auto-fv/permission-check';
export const SCRATCH_FILE = `${SCRATCH_DIR}/PermissionCheck.lean`;
const SCRATCH_CONTENT = '-- FVS permission check: a harmless scratch file that nothing imports.\ndef fvsPermissionCheck : Nat := 1\n';
// A session that does not exist: the permission layer decides before ao runs, and ao then fails harmlessly.
const MESSAGE = 'ao send --session fvs-permission-check-no-such-session --message "FVS permission check. Nothing to do."';
const CODEX_MARKER = '# fvs-auto-permissions: generated by /fvs:auto-init; delete this file to undo it';
const WORD = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
// Branch namespaces a run must never be allowed to push to without asking.
const RESERVED = new Set(['main', 'master', 'HEAD', 'head', 'release', 'releases', 'develop', 'dev', 'trunk']);

class Refuse extends Error {
  constructor(code, message, details = {}) { super(message); this.code = code; this.details = details; }
}
const refuse = (code, message, details) => { throw new Refuse(code, message, details); };

// ---- inputs -------------------------------------------------------------------------------------------------

function checkRepo(repo) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*\/[A-Za-z0-9._-]+$/.test(repo ?? '')) refuse('invalid-input', `--repo must be OWNER/REPO, got ${JSON.stringify(repo)}`);
  return repo;
}
function checkRemote(remote) {
  if (!WORD.test(remote)) refuse('invalid-input', `remote name ${JSON.stringify(remote)} is not a plain name`);
  if (remote === 'upstream') refuse('upstream-refused', 'the remote named upstream is never allowed; use the project\'s own repository (usually origin)');
  return remote;
}
function checkPrefix(prefix) {
  const parts = String(prefix).split('/');
  if (!parts.every((part) => WORD.test(part)) || String(prefix).includes('..') || String(prefix).endsWith('.lock')) {
    refuse('invalid-input', `branch prefix ${JSON.stringify(prefix)} must be plain words joined by "/" (no wildcard, colon, dots at the start, or ".."), such as fvs`);
  }
  if (RESERVED.has(parts[0])) refuse('invalid-input', `branch prefix ${JSON.stringify(prefix)} is a shared branch name; choose a namespace of your own, such as fvs`);
  return prefix;
}
function checkEditDir(dir) {
  if (!String(dir).split('/').every((part) => WORD.test(part))) refuse('invalid-input', `edit folder ${JSON.stringify(dir)} must be a plain relative folder such as formal (no dot folders, no "..", no wildcard)`);
  return dir;
}

function repoFromUrl(url) {
  const match = /^(?:[a-z+]+:\/\/(?:[^@/]+@)?[^/:]+(?::\d+)?\/|[^@/\s]+@[^:/\s]+:)([^/\s]+\/[^/\s]+?)(?:\.git)?\/?$/i.exec(url.trim());
  return match ? match[1] : null;
}
// The push target must be the project's own repository: both the fetch and the push URL of the remote must name it.
function checkRemoteIsRepo(root, remote, repo) {
  for (const args of [['get-url'], ['get-url', '--push']]) {
    const run = spawnSync('git', ['-C', root, 'remote', ...args, remote], { encoding: 'utf8' });
    if (run.status !== 0) refuse('remote-missing', `git remote ${remote} is not set in ${root}`);
    const named = repoFromUrl(run.stdout);
    if (!named || named.toLowerCase() !== repo.toLowerCase()) {
      refuse('remote-mismatch', `remote ${remote} points at ${named ?? run.stdout.trim()}, not ${repo}; the check pushes only to the project's own repository`);
    }
  }
}

// ---- the closed catalog -------------------------------------------------------------------------------------

const GUARD_LONG = ['--force', '--delete', '--mirror', '--all', '--tags', '--prune'];
const GUARD_SHORT = ['-f', '-d'];
// Start-anchored deny rules: a leading wildcard would also match message and pull request text.
export const GUARDS = [
  ...GUARD_LONG.map((flag) => `Bash(git push *${flag}*)`),
  ...GUARD_SHORT.flatMap((flag) => [`Bash(git push ${flag}*)`, `Bash(git push * ${flag}*)`]),
  'Bash(git push * +*)',
  'Bash(git push *:*)',
];

const bash = (command) => ({ tool: 'Bash', command });
const rule = (pattern, justification, match, notMatch) => ({ pattern, justification, match, notMatch });

export function buildCatalog({ repo, remote = 'origin', prefixes = ['fvs'], editDir = 'formal' }) {
  checkRepo(repo); checkRemote(remote); checkEditDir(editDir);
  const pushPrefixes = prefixes.map(checkPrefix);
  const prefix = pushPrefixes[0];
  const steps = [
    {
      id: 'worker-message', why: 'The orchestrator sends instructions to its workers.',
      probes: [bash(MESSAGE)],
      claude: ['Bash(ao send *)'],
      codex: [rule(['ao', 'send'], 'Orchestrator messages to workers', ['ao send --session w --message hi'], ['ao stop w'])],
    },
    {
      id: 'author-edit', why: 'An author writes a Lean file. The probe writes one scratch file in the git-excluded run folder.',
      probes: [{ tool: 'Write', path: SCRATCH_FILE, content: SCRATCH_CONTENT }],
      claude: [`Edit(/${SCRATCH_DIR}/**)`],
      codex: [], codexNote: 'Codex file edits follow the sandbox mode, not a rule file.',
    },
    {
      id: 'lake-build', why: 'Authors and the orchestrator compile Lean files with Lake. The probe compiles an import-free file; `plan` skips it while a dependency is missing, because Lake would download it.',
      probes: [bash(`lake env lean ${SCRATCH_FILE}`)],
      claude: ['Bash(lake env lean *)', 'Bash(lake build *)'],
      codex: [], codexNote: 'Codex runs Lake inside its workspace sandbox without a rule.',
    },
    {
      id: 'gh-read', why: 'The orchestrator reads pull requests of the project repository (read only).',
      probes: [bash(`gh pr list --repo ${repo} --limit 1`), bash(`gh pr view 1 --repo ${repo}`)],
      claude: ['Bash(gh pr view *)', 'Bash(gh pr list *)'],
      codex: [
        rule(['gh', 'pr', 'view'], 'Read a pull request', [`gh pr view 1 --repo ${repo}`], ['gh pr merge 1']),
        rule(['gh', 'pr', 'list'], 'List pull requests', [`gh pr list --repo ${repo}`], ['gh pr close 1']),
      ],
    },
    {
      id: 'git-read', why: 'The orchestrator fetches branches and lists remote branches (read only).',
      probes: [bash(`git ls-remote --heads ${remote}`), bash(`git fetch ${remote}`)],
      claude: ['Bash(git fetch *)', 'Bash(git ls-remote *)'],
      codex: [
        rule(['git', 'fetch', remote], `Fetch from ${remote}`, [`git fetch ${remote}`], ['git fetch other']),
        rule(['git', 'ls-remote'], 'List remote branches', [`git ls-remote --heads ${remote}`], ['git push']),
      ],
    },
    {
      id: 'git-push', why: `A worker pushes its branch to the project fork (${remote}), only under ${pushPrefixes.map((p) => `${p}/`).join(' or ')}. The probe is a dry run: nothing is pushed.`,
      probes: pushPrefixes.map((p) => bash(`git push -u ${remote} ${p}/permission-check --dry-run`)),
      claude: pushPrefixes.flatMap((p) => [`Bash(git push -u ${remote} ${p}/*)`, `Bash(git push ${remote} ${p}/*)`]),
      codex: [], codexNote: 'A Codex rule matches only the start of a command, so it cannot exclude a force push: push still asks on Codex.',
      guards: GUARDS,
    },
    {
      id: 'draft-pr-create', optional: true, why: 'A worker opens a draft pull request on the project repository. Not probed: creating one is not harmless.',
      probes: null,
      claude: [`Bash(gh pr create --draft --repo ${repo} *)`],
      codex: [], codexNote: 'Not written for Codex.',
    },
    {
      id: 'draft-pr-edit', optional: true, why: 'A worker edits the body of a pull request. Not probed: editing one is not harmless.',
      probes: null,
      claude: ['Bash(gh pr edit *)'],
      codex: [], codexNote: 'Not written for Codex.',
    },
    {
      id: 'edit-folders', optional: true, why: `Authors edit files under ${editDir}/ without asking each time. Not probed: a probe there would leave a stray file in a folder that is committed.`,
      probes: null,
      claude: [`Edit(/${editDir}/**)`],
      codex: [], codexNote: 'Codex file edits follow the sandbox mode, not a rule file.',
    },
  ];
  return { repo, remote, prefixes: pushPrefixes, editDir, steps, guards: GUARDS };
}

// Defence in depth: every rule the writer is about to emit passes this, whatever built it.
export function ruleProblem(kind, text) {
  if (kind === 'deny') return GUARDS.includes(text) ? null : 'only the push guard rules may be written as deny rules';
  if (kind !== 'allow') return `unknown rule kind ${kind}`;
  const edit = /^Edit\(\/(.+)\/\*\*\)$/.exec(text);
  if (edit) {
    if (edit[1] === SCRATCH_DIR) return null;
    return edit[1].split('/').every((part) => WORD.test(part)) ? null : 'an edit rule must name a plain folder (no dot folders such as .claude or .git, no "..")';
  }
  const push = /^Bash\(git push (?:-u )?(\S+) (\S+)\/\*\)$/.exec(text);
  if (push) {
    if (!WORD.test(push[1]) || push[1] === 'upstream') return 'a push rule must name the project remote, never upstream';
    const parts = push[2].split('/');
    if (!parts.every((part) => WORD.test(part)) || push[2].includes('..') || RESERVED.has(parts[0])) return 'a push rule must name a private branch namespace, never a shared branch';
    return null;
  }
  const fixed = [/^Bash\(ao send \*\)$/, /^Bash\(gh pr (?:view|list|edit) \*\)$/, /^Bash\(git (?:fetch|ls-remote) \*\)$/,
    /^Bash\(lake (?:env lean|build) \*\)$/, /^Bash\(gh pr create --draft --repo [A-Za-z0-9][A-Za-z0-9._-]*\/[A-Za-z0-9._-]+ \*\)$/];
  return fixed.some((pattern) => pattern.test(text)) ? null : 'not a rule FVS writes (no GitHub comment, review or merge, no force push, no wildcard program)';
}

function selectedRules(catalog, stepIds) {
  const wanted = [...new Set(stepIds)];
  const byId = Object.fromEntries(catalog.steps.map((step) => [step.id, step]));
  for (const id of wanted) if (!byId[id]) refuse('unknown-step', `unknown step ${JSON.stringify(id)}; steps: ${catalog.steps.map((s) => s.id).join(', ')}`);
  if (wanted.length === 0) refuse('invalid-input', '--steps needs at least one step id');
  const picked = wanted.map((id) => byId[id]);
  return { picked, allow: picked.flatMap((step) => step.claude), deny: picked.flatMap((step) => step.guards ?? []) };
}

const digestOf = (value) => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');

// ---- files --------------------------------------------------------------------------------------------------

function writeAtomic(file, text) {
  const target = fs.existsSync(file) ? fs.realpathSync(file) : path.join(fs.realpathSync(path.dirname(file)), path.basename(file));
  const mode = fs.existsSync(target) ? fs.statSync(target).mode & 0o777 : 0o644;
  const temp = `${target}.tmp-${process.pid}`;
  fs.writeFileSync(temp, text, { mode });
  fs.renameSync(temp, target);
  return target;
}
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const plain = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);

function readRecord(root) {
  const file = path.join(root, RECORD_FILE);
  if (!fs.existsSync(file)) return null;
  let value;
  try { value = readJson(file); } catch { refuse('malformed-record', `${file} is not valid JSON; fix or delete it yourself, it is never overwritten`); }
  if (!plain(value) || value.schema !== 'fvs/auto-permissions' || value.schemaVersion !== 1 || !Array.isArray(value.rounds)) {
    refuse('malformed-record', `${file} is not an fvs/auto-permissions record; it is never overwritten`);
  }
  return value;
}

function summaryLine(record) {
  if (!record) return 'not checked';
  const last = record.rounds.at(-1);
  const results = Object.values(last?.results ?? {});
  const prompted = Object.entries(last?.results ?? {}).filter(([, v]) => v === 'prompted').map(([k]) => k);
  const wrote = record.allowlist ? `; allowlist written to ${record.allowlist.file} (${record.allowlist.allow.length} allow, ${record.allowlist.deny.length} deny)` : '';
  // Every step "unknown" is how the owner's decision to skip the check is kept, so it is not asked again.
  const skipped = results.length > 0 && results.every((v) => v === 'unknown');
  const waits = skipped ? '; skipped by the owner, nothing was checked' : prompted.length ? `; waiting for your approval when the run reaches: ${prompted.join(', ')}` : '; no step prompted';
  return `${last?.kind ?? 'check'} on ${(last?.at ?? '').slice(0, 10)} (${record.runtime})${waits}${wrote}`;
}

// ---- commands -----------------------------------------------------------------------------------------------

function context(flags) {
  const root = fs.realpathSync.native(flags['project-root'] ?? process.cwd());
  const catalog = buildCatalog({ repo: flags.repo, remote: flags.remote, prefixes: flags['branch-prefix'], editDir: flags['edit-dir'] });
  checkRemoteIsRepo(root, catalog.remote, catalog.repo);
  return { root, catalog };
}

// `lake env lean` loads the whole workspace: Lake clones a dependency that is missing and writes a manifest that is
// missing. The Lake probe therefore runs only when neither can happen.
export function lakeProbeBlocker(root) {
  const has = (name) => fs.existsSync(path.join(root, name));
  if (!has('lakefile.toml') && !has('lakefile.lean')) return 'there is no lakefile at the project root';
  if (!has('lake-manifest.json')) return 'there is no lake-manifest.json yet and Lake would create one';
  let manifest;
  try { manifest = readJson(path.join(root, 'lake-manifest.json')); } catch { return 'lake-manifest.json is not valid JSON'; }
  const dir = manifest.packagesDir ?? '.lake/packages';
  const missing = (manifest.packages ?? []).filter((pkg) => pkg.type !== 'path' && !fs.existsSync(path.join(root, dir, pkg.name))).map((pkg) => pkg.name);
  return missing.length ? `Lake would download ${missing.join(', ')}, which is not in ${dir}` : null;
}

function plan(flags) {
  const { root, catalog } = context(flags);
  const record = readRecord(root);
  const lakeBlocker = lakeProbeBlocker(root);
  return {
    code: 'ok', record: record ? { present: true, summary: summaryLine(record), rounds: record.rounds } : { present: false, summary: summaryLine(null) },
    repo: catalog.repo, remote: catalog.remote, branchPrefixes: catalog.prefixes,
    steps: catalog.steps.map((step) => (step.id === 'lake-build' && lakeBlocker
      ? { id: step.id, optional: false, why: step.why, probes: null, skipped: `not probed: ${lakeBlocker}; record it as unknown` }
      : { id: step.id, optional: Boolean(step.optional), why: step.why, probes: step.probes })),
    message: record ? 'A record exists: do not run the check again; show the summary.' : 'Run each probe as its own plain call, then ask the user which steps prompted. A skipped step is recorded as unknown.',
  };
}

const RESULTS = new Set(['prompted', 'quiet', 'unknown']);
function record(flags) {
  const { root, catalog } = context(flags);
  if (!flags.input) refuse('invalid-input', '--input is required');
  let input;
  try { input = readJson(flags.input); } catch (error) { refuse('invalid-input', `cannot read --input: ${error.message}`); }
  const ids = new Set(catalog.steps.filter((step) => step.probes).map((step) => step.id));
  const errors = [];
  if (!['claude', 'codex'].includes(input.runtime)) errors.push('runtime must be claude or codex');
  if (!['check', 'recheck'].includes(input.kind)) errors.push('kind must be check or recheck');
  if (!plain(input.results) || Object.keys(input.results).length === 0) errors.push('results must map step ids to prompted, quiet or unknown');
  else for (const [id, value] of Object.entries(input.results)) {
    if (!ids.has(id)) errors.push(`${id} is not a probed step`);
    if (!RESULTS.has(value)) errors.push(`${id}: ${JSON.stringify(value)} is not prompted, quiet or unknown`);
  }
  if (errors.length) refuse('invalid-input', `invalid record input: ${errors.join('; ')}`, { errors });
  const previous = readRecord(root);
  const next = {
    schema: 'fvs/auto-permissions', schemaVersion: 1, runtime: input.runtime, repo: catalog.repo, remote: catalog.remote, branchPrefixes: catalog.prefixes,
    rounds: [...(previous?.rounds ?? []), { at: new Date().toISOString(), kind: input.kind, results: input.results }],
    ...(previous?.allowlist ? { allowlist: previous.allowlist } : {}),
  };
  fs.mkdirSync(path.join(root, path.dirname(RECORD_FILE)), { recursive: true });
  writeAtomic(path.join(root, RECORD_FILE), JSON.stringify(next, null, 2) + '\n');
  return { code: 'recorded', summary: summaryLine(next), prompted: Object.entries(input.results).filter(([, v]) => v === 'prompted').map(([k]) => k) };
}

function gitStatusOf(root, relative) {
  const git = (...args) => spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
  if (git('rev-parse', '--git-dir').status !== 0) return 'not-a-git-repository';
  if (git('check-ignore', '-q', relative).status === 0) return 'ignored';
  return git('ls-files', '--error-unmatch', relative).status === 0 ? 'tracked' : 'untracked-not-ignored';
}

// Claude Code reads settings.local.json from the main checkout, so a copy in a linked worktree would be ignored.
function checkMainCheckout(root) {
  const git = (flag) => spawnSync('git', ['-C', root, 'rev-parse', '--path-format=absolute', flag], { encoding: 'utf8' });
  const dir = git('--git-dir');
  const common = git('--git-common-dir');
  if (dir.status === 0 && common.status === 0 && dir.stdout.trim() !== common.stdout.trim()) {
    refuse('local-needs-main-checkout', `${root} is a linked worktree; Claude Code reads .claude/settings.local.json from the main checkout, so run init there or use --target shared`);
  }
}

function mergeClaude(existing, allow, deny) {
  if (!plain(existing)) refuse('malformed-settings', 'the settings file is not a JSON object; it is never overwritten');
  const permissions = existing.permissions ?? {};
  if (!plain(permissions) || [permissions.allow, permissions.deny].some((list) => list !== undefined && !Array.isArray(list))) {
    refuse('malformed-settings', 'permissions, permissions.allow or permissions.deny has an unexpected shape; the file is never overwritten');
  }
  const merged = structuredClone(existing);
  merged.permissions = merged.permissions ?? {};
  const added = { allow: [], deny: [] };
  for (const [key, rules] of [['allow', allow], ['deny', deny]]) {
    const list = merged.permissions[key] ?? [];
    for (const text of rules) if (!list.includes(text)) { list.push(text); added[key].push(text); }
    if (rules.length) merged.permissions[key] = list;
  }
  return { merged, added };
}

// The merge may only append the new rules: every other key, and every rule already in the file, stays as it was.
function checkNothingElseChanged(existing, merged, added) {
  const problems = [];
  for (const key of Object.keys(merged)) {
    if (key !== 'permissions' && JSON.stringify(merged[key]) !== JSON.stringify(existing[key])) problems.push(key);
  }
  for (const key of Object.keys(existing)) if (!(key in merged)) problems.push(key);
  for (const key of Object.keys(existing.permissions ?? {})) {
    const old = existing.permissions[key];
    const now = merged.permissions[key];
    const same = key === 'allow' || key === 'deny' ? now.length === old.length + added[key].length && old.every((item, i) => now[i] === item) : JSON.stringify(now) === JSON.stringify(old);
    if (!same) problems.push(`permissions.${key}`);
  }
  if (problems.length) refuse('merge-check-failed', `internal check: the merge would change ${problems.join(', ')}; nothing was written`);
}

function confirmationNeeded(flags, digest, preview) {
  if (flags.confirm === digest) return;
  refuse('confirmation-required', flags.confirm ? 'the confirmed digest does not match these rules; show the user this preview again' : 'nothing is written without the user\'s yes: show the user this preview, and only after their yes rerun with --confirm DIGEST',
    { ...preview, digest });
}

function writeAllowlist(flags) {
  const { root, catalog } = context(flags);
  const runtime = flags.runtime;
  if (!['claude', 'codex'].includes(runtime)) refuse('invalid-input', '--runtime must be claude or codex');
  const { picked, allow, deny } = selectedRules(catalog, (flags.steps ?? '').split(',').filter(Boolean));
  for (const text of allow) { const problem = ruleProblem('allow', text); if (problem) refuse('forbidden-rule', `${text}: ${problem}`); }
  for (const text of deny) { const problem = ruleProblem('deny', text); if (problem) refuse('forbidden-rule', `${text}: ${problem}`); }
  return runtime === 'claude' ? writeClaude(flags, root, catalog, picked, allow, deny) : writeCodex(flags, root, catalog, picked);
}

function writeClaude(flags, root, catalog, picked, allow, deny) {
  const target = flags.target ?? 'shared';
  if (!['shared', 'local'].includes(target)) refuse('invalid-input', '--target must be shared or local');
  const relative = `.claude/${target === 'shared' ? 'settings.json' : 'settings.local.json'}`;
  if (target === 'local') checkMainCheckout(root);
  const file = path.join(root, relative);
  let existing = {};
  if (fs.existsSync(file)) {
    try { existing = readJson(file); } catch { refuse('malformed-settings', `${relative} is not valid JSON; fix it yourself first, it is never overwritten`); }
  }
  const { merged, added } = mergeClaude(existing, allow, deny);
  const preview = { runtime: 'claude', file: relative, steps: picked.map((step) => step.id), add: added, alreadyPresent: { allow: allow.filter((r) => !added.allow.includes(r)), deny: deny.filter((r) => !added.deny.includes(r)) } };
  if (added.allow.length + added.deny.length === 0) return { code: 'unchanged', message: `${relative} already holds every rule`, ...preview };
  confirmationNeeded(flags, digestOf({ runtime: 'claude', file: relative, allow: added.allow, deny: added.deny }), preview);
  checkNothingElseChanged(existing, merged, added);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const real = writeAtomic(file, JSON.stringify(merged, null, 2) + '\n');
  const reread = readJson(real);
  if (![...added.allow, ...added.deny].every((text) => [...(reread.permissions.allow ?? []), ...(reread.permissions.deny ?? [])].includes(text))) {
    refuse('write-check-failed', `${real} does not hold the new rules after writing`);
  }
  const previous = readRecord(root);
  if (previous) {
    const kept = previous.allowlist?.file === relative ? previous.allowlist : { file: relative, allow: [], deny: [] };
    writeAtomic(path.join(root, RECORD_FILE), JSON.stringify({ ...previous, allowlist: { file: relative, allow: [...kept.allow, ...added.allow], deny: [...kept.deny, ...added.deny] } }, null, 2) + '\n');
  }
  return {
    code: 'written', ...preview, realPath: real, gitStatus: gitStatusOf(root, relative),
    notes: [
      'Claude Code reloads settings files while running; if a step still prompts, run the check again for that step (see the permissions page).',
      'Worker worktrees read their own .claude/settings.json: it reaches them only if committed or if .claude is linked into them. settings.local.json is read from the main checkout in every worktree.',
    ],
  };
}

const q = (text) => JSON.stringify(text);
function codexFile(rules) {
  const body = rules.map((r) => `prefix_rule(\n    pattern = [${r.pattern.map(q).join(', ')}],\n    decision = "allow",\n    justification = ${q(r.justification)},\n    match = [${r.match.map(q).join(', ')}],\n    not_match = [${r.notMatch.map(q).join(', ')}],\n)\n`);
  return [CODEX_MARKER, '', ...body].join('\n');
}

function writeCodex(flags, root, catalog, picked) {
  const rules = picked.flatMap((step) => step.codex);
  if (rules.length === 0) refuse('nothing-to-write', 'none of these steps can be written as a Codex rule', { reasons: Object.fromEntries(picked.map((s) => [s.id, s.codexNote ?? ''])) });
  const relative = '.codex/rules/fvs-auto.rules';
  const file = path.join(root, relative);
  const text = codexFile(rules);
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').startsWith(CODEX_MARKER)) refuse('foreign-file', `${relative} exists and was not written by FVS; it is never overwritten`);
  const preview = { runtime: 'codex', file: relative, steps: picked.map((s) => s.id), text, notWritten: Object.fromEntries(picked.filter((s) => s.codex.length === 0).map((s) => [s.id, s.codexNote ?? ''])) };
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return { code: 'unchanged', ...preview };
  confirmationNeeded(flags, digestOf({ runtime: 'codex', file: relative, text }), preview);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  writeAtomic(file, text);
  // Codex's own evaluator checks that each rule matches its probe command (it needs the codex CLI on PATH).
  const checks = picked.flatMap((s) => s.codex.flatMap((r) => r.match)).map((command) => {
    const run = spawnSync('codex', ['execpolicy', 'check', '--rules', file, ...command.split(' ')], { encoding: 'utf8' });
    if (run.error || run.status !== 0) return { command, decision: null };
    try { return { command, decision: JSON.parse(run.stdout).decision ?? null }; } catch { return { command, decision: null }; }
  });
  return {
    code: 'written', ...preview, gitStatus: gitStatusOf(root, relative), codexCheck: checks,
    notes: ['Codex loads project rules only when the project .codex/ folder is trusted.', 'Whether a live Codex session stops prompting after this file is not observed.'],
  };
}

// ---- command line -------------------------------------------------------------------------------------------

const USAGE = `Usage: node fvs-auto-permissions.mjs <plan|record|write-allowlist> --repo OWNER/REPO [options]

  --project-root DIR     project root (default: the current directory)
  --repo OWNER/REPO      the project's own repository (where draft pull requests go); the remote must point at it
  --remote NAME          git remote of the project fork (default origin; never upstream)
  --branch-prefix P      branch namespace the run pushes under (repeatable; default fvs; never main, master, release...)
  --edit-dir DIR         spec and proof folder for the optional edit-folders step (default formal)

plan                     list the probes: one harmless instance of each run step, plus the optional steps
record --input FILE      keep the user's answer: {"runtime":"claude|codex","kind":"check|recheck","results":{"<step>":"prompted|quiet|unknown"}}
write-allowlist          --runtime claude|codex --steps ID,ID [--target shared|local] [--confirm DIGEST]
                         without a matching --confirm it writes nothing and prints the preview and its digest

Output is JSON. Exit 0 on success, 1 on a refusal, 2 on a usage error.
`;

function parse(argv) {
  const flags = { 'branch-prefix': [] };
  const known = new Set(['project-root', 'repo', 'remote', 'branch-prefix', 'edit-dir', 'input', 'runtime', 'steps', 'target', 'confirm']);
  for (let i = 0; i < argv.length; i += 2) {
    const name = argv[i]?.startsWith('--') ? argv[i].slice(2) : null;
    if (!name || !known.has(name)) throw new Refuse('usage', `unknown argument ${JSON.stringify(argv[i])}`);
    const value = argv[i + 1];
    if (value === undefined || value.startsWith('--')) throw new Refuse('usage', `--${name} requires a value`);
    if (name === 'branch-prefix') flags[name].push(value); else flags[name] = value;
  }
  if (flags['branch-prefix'].length === 0) flags['branch-prefix'] = ['fvs'];
  return flags;
}

export function main(argv) {
  const [command, ...rest] = argv;
  const commands = { plan, record, 'write-allowlist': writeAllowlist };
  try {
    if (!commands[command]) throw new Refuse('usage', `unknown command ${JSON.stringify(command)}`);
    process.stdout.write(JSON.stringify(commands[command](parse(rest)), null, 2) + '\n');
  } catch (error) {
    if (!(error instanceof Refuse)) throw error;
    process.stdout.write(JSON.stringify({ code: error.code, message: error.message, ...error.details }, null, 2) + '\n');
    process.exitCode = error.code === 'usage' ? 2 : 1;
  }
}

// Run only as a program, never when a test imports the functions above.
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  if (process.argv.includes('--help') || process.argv.includes('-h') || process.argv.length === 2) process.stdout.write(USAGE);
  else main(process.argv.slice(2));
}
