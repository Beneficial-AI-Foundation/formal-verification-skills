// A branch name that no branch can have (git forbids a name component that starts with a dot), so the push command
// refuses it before it contacts the destination. The push probe uses it.
const PROBE_BRANCH = '.permission-check';

class Refuse extends Error {
  constructor(code, message, details = {}) { super(message); this.code = code; this.details = details; }
}
const refuse = (code, message, details) => { throw new Refuse(code, message, details); };

// ---- inputs -------------------------------------------------------------------------------------------------

function checkRepo(repo) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*\/[A-Za-z0-9._-]+$/.test(repo ?? '')) refuse('invalid-input', `--repo must be OWNER/REPO, got ${JSON.stringify(repo)}`);
  return repo;
}
function checkRemote(remote) {
  if (!WORD.test(remote)) refuse('invalid-input', `remote name ${JSON.stringify(remote)} is not a plain name`);
  if (remote === 'upstream') refuse('upstream-refused', 'the remote named upstream is never allowed; use the project\'s own repository (usually origin)');
  return remote;
}
function checkPrefix(prefix) {
  const problem = checkPrefixShape(prefix);
  if (problem) refuse('invalid-input', `branch prefix ${JSON.stringify(prefix)} ${problem}; choose a namespace of your own, such as fvs`);
  return prefix;
}

// ---- the closed catalog -------------------------------------------------------------------------------------

const bash = (command) => ({ tool: 'Bash', command });
const rule = (pattern, justification, match, notMatch) => ({ pattern, justification, match, notMatch });

function checkHost(host) {
  if (!/^[A-Za-z0-9.-]+$/.test(host ?? '')) refuse('invalid-input', `--host must be a plain host name, got ${JSON.stringify(host)}`);
  return host;
}

// A plain absolute path: letters, digits and . _ - / only. A rule that names the push command spells this path out, and
// a space, quote, glob character or other shell syntax in it could not be matched or quoted reliably.
const plainPath = (dir) => /^\/[A-Za-z0-9._/-]+$/.test(dir) && !dir.split('/').includes('..');

export const pushProgram = (scriptsDir = SCRIPTS_DIR) => `node ${scriptsDir}/${PUSH_SCRIPT}`;

