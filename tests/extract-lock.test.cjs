'use strict';

// The Cargo.lock of an extraction copy: read from the project and recorded, or absent and
// refused before an attempt (cargo would write one into the copy during the build), or
// brought in line with the patched manifests once by prepare --lock update (generated when
// there is none, updated when the project's lock needs changes) and recorded by hash.
// Cargo is a fake script; no real tool runs.

const { describe, it, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const { toySpec, cleanup, workspace, run: engine, specFile, step, completeUnit } = require('./helpers/fake-multicrate-tools.cjs');

after(cleanup);

const RELEASE = toySpec().release;
let counter = 0;
const copyOut = (ws) => path.join(ws.root, 'copies', `lock-${(counter += 1)}`);
const withoutLock = (ws) => {
  fs.rmSync(path.join(ws.project, 'Cargo.lock'));
  fs.writeFileSync(path.join(ws.project, '.formalising', 'fvs-config.json'), JSON.stringify({ extraction: { inputs: ['Cargo.toml', 'app', 'lib'] } }));
};
const prepare = (ws, extra = []) => {
  const out = copyOut(ws);
  return { out, done: engine(ws, ['prepare', '--project-root', ws.project, '--out', out, ...extra]) };
};

describe('Cargo.lock of the extraction copy', () => {
  it('records a lock the project has, with its hash', () => {
    const ws = workspace();
    const { done } = prepare(ws);
    assert.equal(done.status, 0, done.stdout);
    const lock = done.result.manifest.lock;
    assert.equal(lock.origin, 'read');
    assert.equal(lock.path, 'Cargo.lock');
    assert.equal(lock.sha256, done.result.manifest.final.files['Cargo.lock'].sha256);
  });

  it('refuses an attempt for a copy without a lock before anything is written', () => {
    const ws = workspace();
    withoutLock(ws);
    const { out, done } = prepare(ws);
    assert.equal(done.status, 0, done.stdout);
    assert.equal(done.result.manifest.lock.origin, 'absent');
    assert.equal(done.result.manifest.lock.sha256, null);
    const attempt = engine(ws, ['attempt', '--out', out, '--spec', specFile(ws, toySpec())]);
    assert.equal(attempt.status, 8, attempt.stdout);
    assert.match(attempt.result.message, /the prepared copy has no Cargo\.lock, so cargo would write one into the copy .* prepare a new copy with --lock update --release DIR/);
    assert.equal(fs.existsSync(path.join(out, 'attempt.json')), false);
  });

  it('generates the lock once in the copy, records it and runs the whole chain on it', () => {
    const ws = workspace();
    withoutLock(ws);
    const { out, done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.status, 0, done.stdout);
    const lock = done.result.manifest.lock;
    assert.equal(lock.origin, 'generated');
    assert.equal(fs.existsSync(path.join(ws.project, 'Cargo.lock')), false, 'the checkout is not touched');
    const inCopy = path.join(out, 'tree', 'Cargo.lock');
    assert.match(fs.readFileSync(inCopy, 'utf8'), /generated by the fake cargo/);
    assert.equal(lock.sha256, done.result.manifest.final.files['Cargo.lock'].sha256);
    const verified = engine(ws, ['verify-tree', '--out', out]);
    assert.equal(verified.status, 0, verified.stdout);
    const attempt = engine(ws, ['attempt', '--out', out, '--spec', specFile(ws, toySpec())]);
    assert.equal(attempt.status, 0, attempt.stdout);
    for (const crate of attempt.result.attempt.order) completeUnit(ws, out, crate);
    const status = engine(ws, ['attempt-status', '--out', out]);
    assert.equal(status.status, 0, status.stdout);
    assert.deepEqual(status.result.run.lock, lock, 'the run says which lock it was built against');
    assert.deepEqual(status.result.run.units.map((unit) => unit.lock.origin), ['generated', 'generated']);
  });

  it('keeps every version a project lock pins and records the lock it started from', () => {
    const ws = workspace();
    const projectLock = path.join(ws.project, 'Cargo.lock');
    const before = fs.readFileSync(projectLock, 'utf8');
    const { out, done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.status, 0, done.stdout);
    const lock = done.result.manifest.lock;
    assert.equal(lock.origin, 'updated');
    assert.equal(lock.from, done.result.manifest.source.files['Cargo.lock'].sha256, 'the project\'s own lock is the starting point');
    assert.notEqual(lock.sha256, lock.from);
    assert.equal(fs.readFileSync(projectLock, 'utf8'), before, 'the checkout is not touched');
    assert.match(fs.readFileSync(path.join(out, 'tree', 'Cargo.lock'), 'utf8'), /updated by the fake cargo/);
  });

  it('records a lock that needed no change as read', () => {
    const ws = workspace();
    fs.writeFileSync(path.join(ws.tools.cargoHome, 'bin', 'lock-current.txt'), '');
    const { done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.status, 0, done.stdout);
    assert.equal(done.result.manifest.lock.origin, 'read');
    assert.equal(done.result.manifest.lock.from, undefined);
  });

  it('reports a failed generation with cargo\'s first lines and records no prepared copy', () => {
    const ws = workspace();
    withoutLock(ws);
    fs.writeFileSync(path.join(ws.tools.cargoHome, 'bin', 'lock-failure.txt'), 'error: failed to get `x` as a dependency\nCaused by:\n  no matching package named `x` found\n');
    const { out, done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.status, 9, done.stdout);
    assert.match(done.result.message, /cargo generate-lockfile failed in the extraction copy: error: failed to get `x` as a dependency \| Caused by: \| no matching package named `x` found/);
    const manifest = JSON.parse(fs.readFileSync(path.join(out, 'manifest.json'), 'utf8'));
    assert.equal(manifest.status, 'partial');
  });

  it('checks the lock flags before anything is written', () => {
    const ws = workspace();
    for (const [extra, pattern] of [
      [['--lock', 'refresh', '--release', RELEASE], /--lock accepts only "update"/],
      [['--lock', 'update'], /--lock update needs --release DIR/],
      [['--release', RELEASE], /--release is for --lock update/],
    ]) {
      const { out, done } = prepare(ws, extra);
      assert.equal(done.status, 2, done.stdout);
      assert.match(done.result.message, pattern);
      assert.equal(step(ws, out, 'charon').status === 0, false);
    }
  });
});

// The lock is not source: its own origin and hash are recorded, an uncommitted or ignored
// one does not make the inputs dirty, and restore checks it on its own.
describe('the lock apart from the source state', () => {
  const git = (ws, ...args) => {
    const done = spawnSync('git', ['-C', ws.project, '-c', 'user.name=fvs', '-c', 'user.email=fvs@example.invalid', '-c', 'commit.gpgsign=false', ...args], { encoding: 'utf8' });
    assert.equal(done.status, 0, done.stderr);
  };
  // A committed project whose Cargo.lock git ignores, so the lock is an untracked file.
  const ignoredLock = (ws) => {
    fs.writeFileSync(path.join(ws.project, '.gitignore'), 'Cargo.lock\n.aeneas\n.formalising\n');
    git(ws, 'init', '-q');
    git(ws, 'add', '-A');
    git(ws, 'commit', '-q', '-m', 'project');
  };

  it('does not count an ignored or uncommitted Cargo.lock as a dirty input, and still counts every other one', () => {
    const ws = workspace();
    ignoredLock(ws);
    const clean = prepare(ws);
    assert.equal(clean.done.status, 0, clean.done.stdout);
    assert.deepEqual(clean.done.result.manifest.source.dirty, []);
    assert.equal(clean.done.result.manifest.lock.origin, 'read');
    fs.writeFileSync(path.join(ws.project, 'app', 'src', 'extra.rs'), 'pub fn extra() {}\n');
    const dirty = prepare(ws);
    assert.deepEqual(dirty.done.result.manifest.source.dirty, ['app/src/extra.rs']);
    const checked = engine(ws, ['check', '--project-root', ws.project]);
    assert.deepEqual(checked.result.source.dirty, ['app/src/extra.rs']);
  });

  it('does not count a committed Cargo.lock that was edited since', () => {
    const ws = workspace();
    git(ws, 'init', '-q');
    git(ws, 'add', '-A');
    git(ws, 'commit', '-q', '-m', 'project');
    fs.appendFileSync(path.join(ws.project, 'Cargo.lock'), '# edited after the commit\n');
    const { done } = prepare(ws);
    assert.deepEqual(done.result.manifest.source.dirty, []);
    assert.equal(done.result.manifest.lock.sha256, done.result.manifest.final.files['Cargo.lock'].sha256, 'the edited lock is the one recorded');
  });

  it('verify-restore accepts the project\'s lock as recorded, and refuses a read lock that changed since prepare', () => {
    const ws = workspace();
    const { out, done } = prepare(ws);
    assert.equal(done.status, 0, done.stdout);
    const ok = engine(ws, ['verify-restore', '--out', out]);
    assert.equal(ok.status, 0, ok.stdout);
    assert.match(ok.result.message, /and so does the project's Cargo\.lock/);
    fs.appendFileSync(path.join(ws.project, 'Cargo.lock'), '# changed after prepare\n');
    const refused = engine(ws, ['verify-restore', '--out', out]);
    assert.equal(refused.status, 3, refused.stdout);
    assert.equal(refused.result.code, 'dirty-original');
    assert.match(refused.result.message, /the project's Cargo\.lock changed since prepare recorded its start .* the lock this extraction used \(read, [0-9a-f]{12}\) no longer comes from this project/);
  });

  it('verify-restore also checks the project\'s lock when the copy has an updated one', () => {
    const ws = workspace();
    const { out, done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.result.manifest.lock.origin, 'updated');
    assert.equal(engine(ws, ['verify-restore', '--out', out]).status, 0);
    fs.appendFileSync(path.join(ws.project, 'Cargo.lock'), '# changed after prepare\n');
    const refused = engine(ws, ['verify-restore', '--out', out]);
    assert.equal(refused.status, 3, refused.stdout);
    assert.match(refused.result.message, /the lock this extraction used \(updated, /);
  });

  it('verify-restore refuses a lock that appeared in a project that had none, for a generated lock', () => {
    const ws = workspace();
    withoutLock(ws);
    const { out, done } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    assert.equal(done.result.manifest.lock.origin, 'generated');
    assert.equal(engine(ws, ['verify-restore', '--out', out]).status, 0);
    fs.writeFileSync(path.join(ws.project, 'Cargo.lock'), 'version = 3\n');
    const refused = engine(ws, ['verify-restore', '--out', out]);
    assert.equal(refused.status, 3, refused.stdout);
    assert.match(refused.result.message, /the project's Cargo\.lock appeared since prepare recorded its start \(none\), so the lock this extraction used \(generated, /);
  });

  it('verify-tree names the lock when a tool rewrote it in the copy', () => {
    const ws = workspace();
    const { out } = prepare(ws, ['--lock', 'update', '--release', RELEASE]);
    fs.appendFileSync(path.join(out, 'tree', 'Cargo.lock'), '# rewritten by cargo\n');
    const refused = engine(ws, ['verify-tree', '--out', out]);
    assert.equal(refused.status, 7, refused.stdout);
    assert.match(refused.result.message, /Cargo\.lock \(Cargo\.lock is the lock recorded as updated, [0-9a-f]{12}: cargo or a tool rewrote it in the copy\)/);
  });
});
